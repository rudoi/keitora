describe("parseVersion / formatVersion", () => {
  it("parses X.Y.Z", () => {
    expect(parseVersion("1.2.3")).toEqual({ major: 1, minor: 2, patch: 3 });
    expect(parseVersion("  0.1.0 ")).toEqual({ major: 0, minor: 1, patch: 0 });
    expect(parseVersion("10.20.30")).toEqual({ major: 10, minor: 20, patch: 30 });
  });
  it("rejects malformed versions, including release candidates", () => {
    for (const bad of ["1.2", "x.y.z", "1.2.3.4", "1.2.3-beta", "1.2.3-rc.1", "", "v1.2.3"]) {
      expect(() => parseVersion(bad)).toThrow(/expected X\.Y\.Z/);
    }
  });
  it("round-trips", () => {
    for (const v of ["0.1.0", "1.20.3"]) expect(formatVersion(parseVersion(v))).toBe(v);
  });
});

describe("bumpVersion", () => {
  it("bumps patch, minor and major with the right resets", () => {
    expect(bumpVersion("1.2.3", "patch")).toBe("1.2.4");
    expect(bumpVersion("1.2.3", "minor")).toBe("1.3.0");
    expect(bumpVersion("1.2.3", "major")).toBe("2.0.0");
    expect(bumpVersion("0.3.0", "patch")).toBe("0.3.1");
    expect(bumpVersion("0.9.9", "minor")).toBe("0.10.0");
  });
  it("rejects an invalid current version", () => {
    expect(() => bumpVersion("0.3.0-rc.1", "patch")).toThrow();
  });
});

describe("parseSetVersion / compareVersions", () => {
  it("normalises valid versions and throws on invalid ones", () => {
    expect(parseSetVersion(" 2.0.0 ")).toBe("2.0.0");
    expect(() => parseSetVersion("2.0")).toThrow();
    expect(() => parseSetVersion("0.4.0-rc.1")).toThrow();
  });
  it("compares versions numerically per component", () => {
    expect(compareVersions("1.0.0", "1.0.1")).toBeLessThan(0);
    expect(compareVersions("1.2.0", "1.1.9")).toBeGreaterThan(0);
    expect(compareVersions("2.0.0", "1.99.99")).toBeGreaterThan(0);
    expect(compareVersions("0.10.0", "0.9.0")).toBeGreaterThan(0);
    expect(compareVersions("0.3.0", "0.3.0")).toBe(0);
  });
});

