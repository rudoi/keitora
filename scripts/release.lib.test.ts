describe("package.json version", () => {
  it("reads the top-level version", () => {
    expect(getPackageJsonVersion(PACKAGE_JSON)).toBe("0.3.0");
    expect(getPackageJsonVersion(crlf(PACKAGE_JSON))).toBe("0.3.0");
  });
  it("changes only the top-level version and keeps formatting", () => {
    const out = setPackageJsonVersion(PACKAGE_JSON, "0.3.1");
    expect(out).toBe(PACKAGE_JSON.replace('"version": "0.3.0"', '"version": "0.3.1"'));
    expect(JSON.parse(out).resolutions.version).toBe("9.9.9");
  });
  it("keeps CRLF line endings", () => {
    const text = crlf(PACKAGE_JSON);
    expect(setPackageJsonVersion(text, "1.0.0")).toBe(
      text.replace('"version": "0.3.0"', '"version": "1.0.0"'),
    );
  });
  it("ignores a nested version that comes before the top-level one", () => {
    const text = '{\n  "engines": { "version": "1.0.0" },\n  "version": "0.3.0"\n}\n';
    expect(setPackageJsonVersion(text, "0.4.0")).toBe(
      '{\n  "engines": { "version": "1.0.0" },\n  "version": "0.4.0"\n}\n',
    );
  });
  it("throws when absent, not a string, or nested only", () => {
    expect(() => getPackageJsonVersion('{ "name": "keitora" }')).toThrow(/no top-level version/);
    expect(() => setPackageJsonVersion('{ "name": "keitora" }', "0.2.0")).toThrow(/no top-level/);
    expect(() => setPackageJsonVersion('{ "version": 3 }', "0.2.0")).toThrow(/no top-level/);
    expect(() => setPackageJsonVersion('{ "a": { "version": "1.0.0" } }', "0.2.0")).toThrow(
      /no top-level/,
    );
  });
});

describe("tauri.conf.json version", () => {
  it("reads the top-level version, not a nested one", () => {
    expect(getTauriConfVersion(TAURI_CONF)).toBe("0.3.0");
    expect(getTauriConfVersion(crlf(TAURI_CONF))).toBe("0.3.0");
  });
  it("changes only the top-level version, byte for byte otherwise", () => {
    const out = setTauriConfVersion(TAURI_CONF, "0.3.1");
    expect(out).toBe(TAURI_CONF.replace('"version": "0.3.0"', '"version": "0.3.1"'));
    const parsed = JSON.parse(out);
    expect(parsed.build.version).toBe("1.1.1");
    expect(parsed.app.windows[0].version).toBe("2.2.2");
    expect(parsed.plugins.note).toContain('"version": "5.5.5"');
  });
  it("keeps CRLF line endings", () => {
    const text = crlf(TAURI_CONF);
    const out = setTauriConfVersion(text, "0.4.0");
    expect(out).toBe(text.replace('"version": "0.3.0"', '"version": "0.4.0"'));
    expect(out.split("\r\n")).toHaveLength(text.split("\r\n").length);
  });
  it("keeps compact formatting", () => {
    expect(setTauriConfVersion('{"productName":"Keitora","version":"0.3.0"}', "0.3.1")).toBe(
      '{"productName":"Keitora","version":"0.3.1"}',
    );
  });
  it("throws without a top-level version", () => {
    expect(() => getTauriConfVersion('{ "build": { "version": "1.0.0" } }')).toThrow();
    expect(() => setTauriConfVersion('{ "build": { "version": "1.0.0" } }', "0.2.0")).toThrow(
      /tauri\.conf\.json has no top-level version/,
    );
    expect(() => getTauriConfVersion('["version"]')).toThrow();
  });
});

