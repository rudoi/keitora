describe("undoSteps", () => {
  const restore = ["checkout", "HEAD", "--", ...BUMPED_FILES];
  it("only restores the bumped files when the commit failed", () => {
    expect(undoSteps("v0.3.1", "written")).toEqual([restore]);
  });
  it("uncommits then restores when the tag failed", () => {
    expect(undoSteps("v0.3.1", "committed")).toEqual([["reset", "--soft", "HEAD~1"], restore]);
  });
  it("deletes the tag, uncommits, then restores when the push failed", () => {
    expect(undoSteps("v0.3.1", "tagged")).toEqual([
      ["tag", "-d", "v0.3.1"],
      ["reset", "--soft", "HEAD~1"],
      restore,
    ]);
  });
  it.each<ReleaseProgress>(["written", "committed", "tagged"])(
    "never resets --hard and always ends by restoring the files (%s)",
    (progress) => {
      const steps = undoSteps("v0.3.1", progress);
      expect(steps.flat()).not.toContain("--hard");
      expect(steps.at(-1)).toEqual(restore);
    },
  );
  it("touches the tag only once it exists", () => {
    expect(undoSteps("v0.3.1", "written").flat()).not.toContain("v0.3.1");
    expect(undoSteps("v0.3.1", "committed").flat()).not.toContain("v0.3.1");
  });
});

