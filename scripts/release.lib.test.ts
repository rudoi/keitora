describe("parseArgs", () => {
  const base = { dryRun: false, skipCiCheck: false, help: false };
  it("accepts a single bump flag", () => {
    expect(parseArgs(["--patch"])).toEqual({ ...base, bump: "patch" });
    expect(parseArgs(["--minor"]).bump).toBe("minor");
    expect(parseArgs(["--major"]).bump).toBe("major");
  });
  it("accepts --set", () => {
    expect(parseArgs(["--set", "1.4.0"])).toEqual({ ...base, setVersion: "1.4.0" });
  });
  it("accepts --dry-run alone (previewing --patch) and with a bump", () => {
    expect(parseArgs(["--dry-run"])).toEqual({ ...base, dryRun: true });
    expect(parseArgs(["--minor", "--dry-run"])).toEqual({ ...base, bump: "minor", dryRun: true });
  });
  it("accepts --skip-ci-check", () => {
    expect(parseArgs(["--patch", "--skip-ci-check"])).toEqual({
      ...base,
      bump: "patch",
      skipCiCheck: true,
    });
  });
  it("accepts --help and -h without a bump", () => {
    expect(parseArgs(["--help"]).help).toBe(true);
    expect(parseArgs(["-h"]).help).toBe(true);
  });
  it("requires a bump flag or --set outside --dry-run", () => {
    expect(() => parseArgs([])).toThrow(/pass --patch/);
    expect(() => parseArgs(["--skip-ci-check"])).toThrow(/pass --patch/);
  });
  it("rejects conflicting bump flags", () => {
    expect(() => parseArgs(["--patch", "--minor"])).toThrow(/Conflicting/);
  });
  it("rejects --set combined with a bump, or given twice", () => {
    expect(() => parseArgs(["--set", "1.0.0", "--patch"])).toThrow(/Cannot combine/);
    expect(() => parseArgs(["--set", "1.0.0", "--set", "2.0.0"])).toThrow(/more than once/);
  });
  it("rejects --set without a value", () => {
    expect(() => parseArgs(["--set"])).toThrow(/requires/);
    expect(() => parseArgs(["--set", "--dry-run"])).toThrow(/requires/);
    expect(() => parseArgs(["--set", "-h"])).toThrow(/requires/);
  });
  it("rejects an invalid --set version", () => {
    expect(() => parseArgs(["--set", "v1.0.0"])).toThrow();
    expect(() => parseArgs(["--set", "1.0.0-rc.1"])).toThrow();
  });
  it("rejects unknown arguments, including removed flags", () => {
    expect(() => parseArgs(["--bogus"])).toThrow(/Unknown/);
    expect(() => parseArgs(["--overwrite"])).toThrow(/Unknown/);
    expect(() => parseArgs(["patch"])).toThrow(/Unknown/);
  });
});

